#!/usr/bin/env python3
"""Tables of a replay session (`sdkbench.py run --replay ...`). Called by render.py for a session whose provenance names a
replay; every number comes from the session's `cells.jsonl`, its raw samples, and the recording files it names.

Per cell (client, api, mode, concurrency) and over the valid repetitions:
- CPU per request: (client user + system CPU of the measured window) / verified requests, in microseconds.
- Residual: mean client latency minus the mean time the peer took to send the replies of the window (the recorded time from
  the end of a request to its last body piece, plus the peer's lag behind that schedule). It is what the client added on
  top of the provider's pace:
  request construction, the exchange over loopback, decoding, and any wait it imposed. Means are used because the set of
  requests is the same on both sides, so the difference is exact for the mean and not for a percentile.
- Peer lag: how far behind its schedule the peer finished a reply, on average (timer granularity and load of the peer).
  The residual already excludes it; a large lag still marks a peer that could not keep the recorded pace.
"""
from __future__ import annotations

import gzip
import hashlib
import json
import statistics
from collections import defaultdict
from pathlib import Path

HARNESS = Path(__file__).resolve().parents[1]
LAG_BOUND_US = 2000  # a cell whose peer lag exceeds this is marked


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()] if path.exists() else []


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(headers))) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def f1(v: float) -> str:
    return f"{v:,.0f}" if abs(v) >= 100 else f"{v:.1f}" if abs(v) >= 10 else f"{v:.2f}"


def rng(values: list[float]) -> str:
    return f" [{f1(min(values))}–{f1(max(values))}]" if len(values) > 1 and min(values) != max(values) else ""


def recordings_table(prov: dict) -> str:
    rp = prov["replay"]
    rows = []
    for key, meta in sorted(rp["files"].items()):
        path = HARNESS / "replay" / "recordings" / rp["directory"] / meta["file"]
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != meta["sha256"]:
            raise SystemExit(f"{path}: differs from the file the session replayed")
        recs = json.loads(data)["recordings"]
        head = statistics.median(r["head_us"] for r in recs) / 1000
        end = statistics.median(r["chunks"][-1][0] for r in recs) / 1000
        pieces = statistics.median(len(r["chunks"]) for r in recs)
        deltas = statistics.median(r["deltas"] for r in recs)
        rows.append([f"`{key}`", f"`{meta['model']}`", str(len(recs)), f1(head), f1(end), f"{pieces:g}",
                     f"{deltas:g}" if key.endswith("stream") else "–", f"{statistics.median(r['body_bytes'] for r in recs):g}"])
    return table(["api/mode", "model", "recordings", "head p50 (ms)", "last piece p50 (ms)", "body pieces p50", "text deltas p50", "body bytes p50"], rows)


def render(sessions: list[Path]) -> str:
    provs, records = [], []
    for s in sessions:
        provs.append(json.loads((s / "session.json").read_text()))
        records += [(s, r) for r in load_jsonl(s / "cells.jsonl")]
    out = []
    w = out.append
    w("# SDK comparison tables: replay of recorded provider responses\n")
    w("Generated by `render.py` from the records of this session; nothing here is typed by hand. "
      "Method and definitions: `replay/README.md`.\n")
    w("## Provenance\n")
    for p in provs:
        w(f"- Session `{p['session']}`: harness commit `{p['harness_commit'][:12]}`{' (dirty tree)' if p['harness_dirty'] else ''}, "
          f"{p['cpu_model']} × {p['cpu_count']}, kernel {p['kernel']}, governor {p['cpu_governor']}, {p['utc']}. "
          f"Client CPUs `{p['client_cpus']}`, peer CPUs `{p['peer_cpus']}`, {p['peer_workers']} peer processes. "
          f"Workload `{p['workload_file']}`, recordings `{p['replay']['directory']}`.")
    w("")
    w("## Recordings\n")
    w(recordings_table(provs[0]))
    w("Times are from the moment the request was handed to the socket at recording time, so they include the network path "
      "from the recording machine to the provider.\n")
    cells: dict[tuple, list[dict]] = defaultdict(list)
    na = {}
    for s, r in records:
        if r["status"] == "n/a":
            na[(r["client"], r["api"], r["mode"])] = r["reason"]
            continue
        cells[(r["api"], r["mode"], r["concurrency"], r["client"])].append((s, r))
    groups = sorted({(a, m, c) for a, m, c, _ in cells}, key=lambda k: (k[0], k[1], k[2]))
    w("## Results\n")
    w("CPU per request and residual are the median over the valid repetitions, with the range in brackets. "
      "p50 is the median client latency over all samples of the valid repetitions; it is dominated by the recorded pace.\n")
    for api, mode, conc in groups:
        rows = []
        for (a, m, c, client), rs in sorted(cells.items()):
            if (a, m, c) != (api, mode, conc):
                continue
            ok = [(s, r) for s, r in rs if r["status"] == "ok"]
            bad = len(rs) - len(ok)
            if not ok:
                rows.append((float("inf"), [f"`{client}`", "–", "–", "–", "–", "–", f"0 of {len(rs)}"]))
                continue
            cpu, resid, lag, samples, rss = [], [], [], [], []
            for s, r in ok:
                res = r["result"]
                cpu.append((res["cpu_user_us"] + res["cpu_sys_us"]) / res["ok"])
                with gzip.open(s / r["samples_path"], "rt") as fh:
                    lat = [x for x in json.load(fh) if x]
                samples += lat
                resid.append(statistics.fmean(lat) / 1e6 - (r["replay"]["scheduled_mean_us"] + r["replay"]["late_mean_us"]) / 1e3)
                lag.append(r["replay"]["late_mean_us"])
                rss.append(res.get("hwm_end_kb", 0) / 1024)
            p50 = statistics.median(samples) / 1e6
            lag_mark = " ⚠" if max(lag) > LAG_BOUND_US else ""
            rows.append((statistics.median(cpu), [
                f"`{client}`", f1(statistics.median(cpu)) + rng(cpu), f1(statistics.median(resid)) + rng(resid), f1(p50),
                f"{max(rss):.0f}", f1(statistics.median(lag)) + lag_mark, f"{len(ok)} of {len(rs)}" + (f" ({bad} invalid)" if bad else "")]))
        rows.sort(key=lambda x: x[0])
        w(f"### {api} / {mode} / concurrency {conc}\n")
        w(table(["client", "CPU per request (µs)", "residual (ms)", "p50 latency (ms)", "peak RSS (MB)", "peer lag (µs)", "valid repetitions"],
                [r for _, r in rows]))
    if na:
        w("## Not applicable\n")
        for (client, api, mode), reason in sorted(na.items()):
            w(f"- `{client}` {api}/{mode}: {reason}")
        w("")
    invalid = [(s, r) for s, r in records if r["status"] in ("invalid", "error")]
    if invalid:
        w("## Invalid attempts\n")
        w("Every attempt stays in the records; the tables use the valid ones.\n")
        for _, r in invalid:
            reasons = "; ".join(r.get("invalid_reasons", [])) or r.get("reason", "")
            w(f"- `{r['cell']}` attempt {r.get('attempt', 0)}: {reasons}")
        w("")
    w(f"⚠ marks a cell whose mean peer lag exceeds {LAG_BOUND_US} µs.\n")
    return "\n".join(out)
