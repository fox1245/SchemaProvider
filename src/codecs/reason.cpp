std::span<const Entry> entries(Source source) noexcept {
  switch (source) {
    case Source::Chat: return chat_table;
    case Source::Messages: return messages_table;
    case Source::Responses: return responses_table;
    case Source::Gemini: return gemini_table;
    case Source::Interactions: return interactions_table;
    case Source::Accumulator: return accumulator_table;
    case Source::ChatRequest: return chat_request_table;
    case Source::MessagesRequest: return messages_request_table;
    case Source::ResponsesRequest: return responses_request_table;
    case Source::GeminiRequest: return gemini_request_table;
    case Source::InteractionsRequest: return interactions_request_table;
    case Source::SharedRequest: return shared_request_table;
  }
  return {};
}
std::string_view code(Source source, std::string_view message) noexcept {
  for (const auto& entry : entries(source))
    if (entry.message == message) return entry.code;
  return {};
}
std::string_view request_code(Source family_encoder, std::string_view message) noexcept {
  const auto own = code(family_encoder, message);
  return own.empty() ? code(Source::SharedRequest, message) : own;
}
