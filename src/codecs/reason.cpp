std::span<const Entry> entries(Source source) noexcept {
  switch (source) {
    case Source::Chat: return chat_table;
    case Source::Messages: return messages_table;
    case Source::Responses: return responses_table;
    case Source::Gemini: return gemini_table;
    case Source::Interactions: return interactions_table;
    case Source::Accumulator: return accumulator_table;
  }
  return {};
}
std::string_view code(Source source, std::string_view message) noexcept {
  for (const auto& entry : entries(source))
    if (entry.message == message) return entry.code;
  return {};
}
